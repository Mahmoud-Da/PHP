<?php

$first_number = 5; 
$last_number = 10;

// 5 is larger than 10?
var_dump($first_number > $last_number);


var_dump($first_number < $last_number);

var_dump($first_number >= $last_number);


var_dump($first_number <= $last_number);

// equal
// not check data type
var_dump("5" == 5);

// check data type
var_dump("5" === 5);

// not equal
var_dump("5" != 5);
var_dump("5" !== 5);
